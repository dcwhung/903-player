#!/usr/bin/env node
/*
 * importLibrary.mjs：repo 內建 library（apps/player/src/catalog/{shows,dramas}/library/）→ D1 + R2（Backend Phase 2a migration）。
 *
 *   node scripts/importLibrary.mjs --local|--remote [--dry-run] [--overwrite] [--out-dir <dir>]
 *
 * 1. 掃 library（同 buildCatalogJson.mjs 共用 scanLibrary，唔重寫規則）
 * 2. 每張圖算 SHA-256 → R2 key catalog/v1/img/<前 16 hex>.<ext>
 * 3. 寫 <out-dir>/import.sql：預設 INSERT … ON CONFLICT DO NOTHING（只加未有嘅 entries；D1 已有嘅行係 admin 改過嘅 SSoT，唔郁）
 * 4. 問 D1 已有邊啲圖（assets table）同 entries：淨係上載未有嘅圖（wrangler r2 object put），印出 entries 會點
 * 5. 圖上載完先跑 SQL（assets 行 = R2 已經有）
 * --overwrite：entries 改用 ON CONFLICT DO UPDATE，D1 已有而同 repo 唔同嘅行會畀 repo 版本蓋過（admin 嘅改動冇得救返；schedules 唔郁）
 * --dry-run：淨係讀 D1 + 印出要跑嘅指令。要喺 apps/api 跑（wrangler.toml 喺度）。只用 Node 內置 module
 * 兩個 mode 重跑都係 no-op
 */
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { scanLibrary } from '../../player/scripts/buildCatalogJson.mjs';

const DATABASE = '903-player';
const BUCKET = '903-player-catalog';
/** 同 src/config.ts CATALOG_IMAGE_KEY_PREFIX / IMAGE_FILE_PATTERN 一致 */
const IMAGE_KEY_PREFIX = 'catalog/v1/img/';
const HASH_HEX_LENGTH = 16;
const CONTENT_TYPES = { webp: 'image/webp', jpg: 'image/jpeg' };
const EXIT = { ok: 0, failed: 1, usage: 2 };
const API_DIR = fileURLToPath(new URL('../', import.meta.url));
const DEFAULT_OUT_DIR = join(API_DIR, '.import');
const USAGE =
    'usage: node scripts/importLibrary.mjs --local|--remote [--dry-run] [--overwrite] [--out-dir <dir>]';
const BYTES_PER_MEBIBYTE = 1024 ** 2;
/** entries 一次過讀晒 definition；超過 spawnSync 預設 1 MiB 會當 wrangler 失敗 */
const WRANGLER_STDOUT_MAX_BYTES = 64 * BYTES_PER_MEBIBYTE;
/** D1 已有嘅行 = admin 改過嘅 SSoT：預設唔郁（AU-017） */
const KEEP_EXISTING = 'DO NOTHING';
/** --overwrite：內容冇變就唔郁（連 updated_at 都唔改）→ 重跑 = no-op */
const REPLACE_EXISTING =
    'DO UPDATE SET definition = excluded.definition, images = excluded.images, ' +
    'updated_at = excluded.updated_at ' +
    'WHERE entries.definition IS NOT excluded.definition OR entries.images IS NOT excluded.images';
/** repo entry 對 D1 現有行嘅狀態（countEntries 嘅 key） */
const ENTRY_STATE = { missing: 'missing', changed: 'changed', unchanged: 'unchanged' };

const extensionOf = (file) => file.split('.').at(-1).toLowerCase();

const assetOf = ({ file, path }) => {
    const bytes = readFileSync(path);
    const hash = createHash('sha256').update(bytes).digest('hex').slice(0, HASH_HEX_LENGTH);
    const ext = extensionOf(file);
    const contentType = CONTENT_TYPES[ext];
    if (!contentType) throw new Error(`unsupported image type: ${path}`);
    return {
        hash,
        key: `${IMAGE_KEY_PREFIX}${hash}.${ext}`,
        path,
        contentType,
        bytes: bytes.length,
    };
};

const planEntry = (kind, assets) => (entry) => ({
    kind,
    id: entry.id,
    definition: entry.definition,
    images: Object.fromEntries(
        entry.images.map((image) => {
            const asset = assetOf(image);
            if (!assets.has(asset.hash)) assets.set(asset.hash, asset);
            return [image.file, asset.key.slice(IMAGE_KEY_PREFIX.length)];
        }),
    ),
});

/** scanLibrary 結果 → D1 entries + 要上載嘅圖（同一張圖只出現一次） */
export function planImport(library) {
    const assets = new Map();
    const entries = [
        ...library.shows.map(planEntry('shows', assets)),
        ...library.dramas.map(planEntry('dramas', assets)),
    ];
    return { entries, assets: [...assets.values()] };
}

/** SQLite 字串 literal：單引號 double */
const quote = (text) => `'${String(text).replaceAll("'", "''")}'`;

const assetSql = (asset, now) =>
    `INSERT INTO assets (hash, content_type, bytes, created_at) VALUES (${quote(asset.hash)}, ` +
    `${quote(asset.contentType)}, ${asset.bytes}, ${quote(now)}) ON CONFLICT (hash) DO NOTHING;`;

/** D1 存嘅 definition / images 文字；SQL 同 countEntries 用同一個寫法先比較得啱 */
const storedText = (entry) => ({
    definition: JSON.stringify(entry.definition),
    images: JSON.stringify(entry.images),
});

const entrySql = (entry, now, onConflict) => {
    const { definition, images } = storedText(entry);
    return (
        `INSERT INTO entries (kind, id, definition, images, updated_at) VALUES (${quote(entry.kind)}, ` +
        `${quote(entry.id)}, ${quote(definition)}, ${quote(images)}, ${quote(now)}) ` +
        `ON CONFLICT (kind, id) ${onConflict};`
    );
};

/** 一句一行（JSON.stringify 唔會出真換行），wrangler d1 execute --file 同 test 都逐句跑 */
export function importSql(plan, { now = new Date().toISOString(), overwrite = false } = {}) {
    const onConflict = overwrite ? REPLACE_EXISTING : KEEP_EXISTING;
    const lines = [
        '-- generated by apps/api/scripts/importLibrary.mjs（idempotent，可以重跑）',
        ...plan.assets.map((asset) => assetSql(asset, now)),
        ...plan.entries.map((entry) => entrySql(entry, now, onConflict)),
    ];
    return `${lines.join('\n')}\n`;
}

const entryKey = ({ kind, id }) => JSON.stringify([kind, id]);

const entryState = (entry, row) => {
    if (!row) return ENTRY_STATE.missing;
    const { definition, images } = storedText(entry);
    const same = row.definition === definition && row.images === images;
    return same ? ENTRY_STATE.unchanged : ENTRY_STATE.changed;
};

/** repo entries 對 D1 現有行：missing = D1 冇；changed = 有但內容唔同；unchanged = 一樣 */
export function countEntries(entries, existingRows) {
    const existing = new Map(existingRows.map((row) => [entryKey(row), row]));
    const counts = { missing: 0, changed: 0, unchanged: 0 };
    entries.forEach((entry) => {
        counts[entryState(entry, existing.get(entryKey(entry)))] += 1;
    });
    return counts;
}

const keptSummary = ({ missing, changed, unchanged }) =>
    `entries: ${missing} to insert, ${changed + unchanged} existing kept ` +
    `(${changed} differ from the repo library)\n` +
    'existing entries are never modified (pass --overwrite to replace them with the repo library)\n';

const overwriteSummary = ({ missing, changed, unchanged }) =>
    `entries: ${missing} to insert, ${changed} to overwrite, ${unchanged} unchanged\n` +
    `WARNING: --overwrite replaces ${changed} existing entries with the repo library version; ` +
    'admin edits to them cannot be recovered and schedules are not touched\n';

/** wrangler 參數（唔包 `wrangler` 本身） */
export function uploadCommands(assets, mode) {
    return assets.map((asset) => [
        'r2',
        'object',
        'put',
        `${BUCKET}/${asset.key}`,
        '--file',
        asset.path,
        '--content-type',
        asset.contentType,
        `--${mode}`,
    ]);
}

const defaultExec = (args) => {
    const result = spawnSync('npx', ['wrangler', ...args], {
        cwd: API_DIR,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'inherit'],
        maxBuffer: WRANGLER_STDOUT_MAX_BYTES,
    });
    return { status: result.status ?? EXIT.failed, stdout: result.stdout ?? '' };
};

const parseCli = (argv) => {
    const { values } = parseArgs({
        args: argv,
        options: {
            local: { type: 'boolean' },
            remote: { type: 'boolean' },
            'dry-run': { type: 'boolean' },
            overwrite: { type: 'boolean' },
            'out-dir': { type: 'string' },
        },
    });
    if (Boolean(values.local) === Boolean(values.remote))
        throw new Error('pick --local or --remote');
    return {
        mode: values.local ? 'local' : 'remote',
        dryRun: Boolean(values['dry-run']),
        overwrite: Boolean(values.overwrite),
        outDir: values['out-dir'] ?? DEFAULT_OUT_DIR,
    };
};

class WranglerError extends Error {}

const wrangler = (exec, args) => {
    const result = exec(args);
    if (result.status !== 0) throw new WranglerError(`wrangler ${args.join(' ')} failed`);
    return result.stdout;
};

/** 讀 D1（dry run 都會跑）：一句 SELECT 嘅結果行 */
const queryRows = (exec, mode, sql) => {
    const args = ['d1', 'execute', DATABASE, `--${mode}`, '--json', '--command', sql];
    const [result] = JSON.parse(wrangler(exec, args));
    return result?.results ?? [];
};

/** D1 assets table 已有嘅 hash（= R2 已經有，唔使再上載） */
const existingHashes = (exec, mode) =>
    new Set(queryRows(exec, mode, 'SELECT hash FROM assets').map((row) => row.hash));

const existingEntries = (exec, mode) =>
    queryRows(exec, mode, 'SELECT kind, id, definition, images FROM entries');

const writeSql = (plan, { outDir, overwrite }) => {
    mkdirSync(outDir, { recursive: true });
    const file = join(outDir, 'import.sql');
    writeFileSync(file, importSql(plan, { overwrite }));
    return file;
};

const entrySummary = (plan, options, exec) => {
    const counts = countEntries(plan.entries, existingEntries(exec, options.mode));
    return options.overwrite ? overwriteSummary(counts) : keptSummary(counts);
};

const importAll = (options, { out, exec }) => {
    const plan = planImport(scanLibrary());
    const sqlFile = writeSql(plan, options);
    const known = existingHashes(exec, options.mode);
    const uploads = uploadCommands(
        plan.assets.filter((a) => !known.has(a.hash)),
        options.mode,
    );
    const steps = [...uploads, ['d1', 'execute', DATABASE, `--${options.mode}`, '--file', sqlFile]];
    // 第一行格式 import-catalog.yml 嘅 Summary 會 grep，唔好改
    out(
        `${plan.entries.length} entries, ${plan.assets.length} images (${uploads.length} to upload)\n`,
    );
    out(entrySummary(plan, options, exec));
    steps.forEach((args) => {
        out(`wrangler ${args.join(' ')}\n`);
        if (!options.dryRun) wrangler(exec, args);
    });
    return EXIT.ok;
};

/** CLI：成功 0；wrangler 失敗 1；參數錯 2 */
export async function run(
    argv,
    { out = (text) => process.stdout.write(text), exec = defaultExec } = {},
) {
    let options;
    try {
        options = parseCli(argv);
    } catch (error) {
        out(`${error.message}\n${USAGE}\n`);
        return EXIT.usage;
    }
    try {
        return importAll(options, { out, exec });
    } catch (error) {
        if (!(error instanceof WranglerError)) throw error;
        out(`${error.message}\n`);
        return EXIT.failed;
    }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    process.exitCode = await run(process.argv.slice(2));
}
